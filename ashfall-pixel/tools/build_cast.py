def src_path(name):
    for cand in (f'out/ai/{name}-codex-1.png', f'out/ai/{name}.png', f'out/{name}.png'):
        p = os.path.join(ROOT, cand)
        if os.path.exists(p):
            return p
    return None


def cutout(path, tol=22):
    """Flood-fill the plain background from the borders; return a trimmed RGBA image."""
    im = np.asarray(Image.open(path).convert('RGB')).astype(int)
    H, W, _ = im.shape
    bg = np.median(np.concatenate([im[0], im[-1], im[:, 0], im[:, -1]]), axis=0)
    close = np.abs(im - bg).sum(-1) <= tol * 3
    alpha = np.full((H, W), 255, np.uint8)
    seen = np.zeros((H, W), bool)
    q = deque((y, x) for y in (0, H - 1) for x in range(W) if close[y, x])
    q.extend((y, x) for x in (0, W - 1) for y in range(H) if close[y, x])
    for y, x in q:
        seen[y, x] = True
    while q:
        y, x = q.popleft()
        alpha[y, x] = 0
        for ny, nx in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
            if 0 <= ny < H and 0 <= nx < W and not seen[ny, nx] and close[ny, nx]:
                seen[ny, nx] = True
                q.append((ny, nx))
    img = Image.fromarray(np.dstack([im.astype(np.uint8), alpha]), 'RGBA')
    return img.crop(img.getbbox())


def block_size(path):
    """Size of one art pixel in an upscaled pixel-art image: the most common run between colour changes."""
    a = np.asarray(Image.open(path).convert('RGB')).astype(int)
    runs = {}
    for y in range(0, a.shape[0], 5):
        ch = np.where(np.abs(np.diff(a[y], axis=0)).sum(-1) > 40)[0]
        for r in np.diff(ch):
            if 5 <= r <= 40:
                runs[int(r)] = runs.get(int(r), 0) + 1
    best = max(runs, key=runs.get)
    # average with the neighbouring run lengths (blocks are rarely exact integers)
    num = sum(r * runs.get(r, 0) for r in (best - 1, best, best + 1))
    den = sum(runs.get(r, 0) for r in (best - 1, best, best + 1))
    return num / den


def native(img, target_h=None, block=None):
    """Shrink an upscaled pixel-art sprite to its art-pixel grid: each block takes its most common colour."""
    a = np.asarray(img)
    if block:
        target_h = max(1, round(img.height / block))
    k = img.height / target_h
    w = max(1, round(img.width / k))
    out = np.zeros((target_h, w, 4), np.uint8)
    for y in range(target_h):
        for x in range(w):
            blk = a[int(y * k):max(int(y * k) + 1, int((y + 1) * k)), int(x * k):max(int(x * k) + 1, int((x + 1) * k))].reshape(-1, 4)
            op = blk[blk[:, 3] >= 128]
            if len(op) * 2 < len(blk):
                continue
            v, c = np.unique(op[:, :3], axis=0, return_counts=True)
            out[y, x, :3] = v[c.argmax()]
            out[y, x, 3] = 255
    return Image.fromarray(out, 'RGBA')


def font(size):
    for f in ('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'):
        if os.path.exists(f):
            return ImageFont.truetype(f, size)
    return ImageFont.load_default(size)


def main():
    os.makedirs(CAST_DIR, exist_ok=True)
    done = []
    for cid, name, role, hi, px, nh in CAST:
        hp, pp = src_path(hi), src_path(px)
        if not hp or not pp:
            print('skip (missing art):', cid, hi if not hp else px)
            continue
        hi_img = cutout(hp)
        hi_img.save(os.path.join(CAST_DIR, f'{cid}.png'))
        px_big = cutout(pp)
        px_img = native(px_big, block=block_size(pp))
        px_img.save(os.path.join(CAST_DIR, f'{cid}_px.png'))
        px_img.resize((px_img.width * 4, px_img.height * 4), Image.NEAREST).save(os.path.join(CAST_DIR, f'{cid}_px4.png'))
        done.append((cid, name, role, hi_img, px_img))
        print(f'{cid}: hi {hi_img.size}, low {px_img.size}')

    # ---- the sheet: one column per character, high-res on top (common height), low-res below (common pixel scale)
    HI_H, PX_S, COL_W, PAD = 420, 4, 300, 24
    widths = [max(COL_W, p.width * PX_S + 30) for *_, p in done]
    title_f, name_f, role_f = font(44), font(26), font(15)
    max_px_h = max(p.height for *_, p in done) * PX_S
    sheet_w = PAD + sum(widths) + PAD
    sheet_h = 110 + HI_H + 40 + max_px_h + 120
    sheet = Image.new('RGBA', (sheet_w, sheet_h), (28, 22, 34, 255))
    d = ImageDraw.Draw(sheet)
    d.text((PAD, 28), 'ASHFALL · SPRITE CAST', fill=(217, 179, 80), font=title_f)
    d.line([(PAD, 96), (sheet_w - PAD, 96)], fill=(61, 54, 56), width=2)
    base_hi = 110 + HI_H
    base_px = base_hi + 40 + max_px_h
    for i, (cid, name, role, hi_img, px_img) in enumerate(done):
        cx = PAD + sum(widths[:i]) + widths[i] // 2
        s = min(HI_H / hi_img.height, (widths[i] - 20) / hi_img.width)
        h = hi_img.resize((round(hi_img.width * s), round(hi_img.height * s)), Image.LANCZOS)
        sheet.alpha_composite(h, (cx - h.width // 2, base_hi - h.height))
        p = px_img.resize((px_img.width * PX_S, px_img.height * PX_S), Image.NEAREST)
        sheet.alpha_composite(p, (cx - p.width // 2, base_px - p.height))
        tw = d.textlength(name, font=name_f)
        d.text((cx - tw / 2, base_px + 18), name, fill=(233, 223, 196), font=name_f)
        # wrap the role line to the column
        words, line, y = role.split(), '', base_px + 54
        for wd in words:
            t = (line + ' ' + wd).strip()
            if d.textlength(t, font=role_f) > widths[i] - 26:
                d.text((cx - d.textlength(line, font=role_f) / 2, y), line, fill=(169, 156, 148), font=role_f)
                line, y = wd, y + 19
            else:
                line = t
        d.text((cx - d.textlength(line, font=role_f) / 2, y), line, fill=(169, 156, 148), font=role_f)
    out = os.path.join(ROOT, 'out', 'cast-sheet.png')
    sheet.convert('RGB').save(out)
    print('sheet', out, sheet.size)

    # ---- docs/CAST.md
    rows = ['| | High-res | Low-res (×4) |', '|---|---|---|']
    for cid, name, role, *_ in done:
        rows.append(f'| **{name}**<br>{role} | <img src="../cast/{cid}.png" height="220"> | <img src="../cast/{cid}_px4.png" height="160"> |')
    md = ('# Ashfall · Sprite cast\n\n'
          'Every character as a high-res sprite and a low-res game sprite. Generated on the ChatGPT plan '
          '(prompts in `data/art_prompts.json`), cut out and laid out by `tools/build_cast.py`.\n\n'
          '![The cast](../out/cast-sheet.png)\n\n' + '\n'.join(rows) + '\n\n'
          'Low-res files: `cast/<id>_px.png` is native size (one art pixel per image pixel) for the game engine; '
          '`cast/<id>_px4.png` is the same scaled ×4 for viewing.\n')
    open(os.path.join(ROOT, 'docs', 'CAST.md'), 'w').write(md)
    print('docs/CAST.md written,', len(done), 'characters')


if __name__ == '__main__':
    main()
