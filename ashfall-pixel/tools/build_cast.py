"""Build the sprite cast: cut out every character (high-res + low-res) and lay them out on one sheet.

    python3 tools/build_cast.py

Inputs : out/ai/<source>-codex-1.png (generated by tools/gen_codex.py, see data/art_prompts.json)
Outputs: cast/<id>.png          high-res sprite, transparent, trimmed
         cast/<id>_px.png       low-res sprite at its native pixel size (1 art pixel = 1 image pixel)
         cast/<id>_px4.png      the same, scaled x4 with nearest-neighbour for viewing
         out/cast-sheet.png     every character side by side: high-res on top, low-res below, names
         docs/CAST.md           the cast page (renders on GitHub)
"""
